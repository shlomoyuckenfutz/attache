"""Inject the manual-text override loader into the public pages (idempotent).

For each page in content/sections.json this writes one <!--EDITOV--> block before </body>:
  <script id="edit-ov" type="application/json">{page, base, sections for the page, active overrides}</script>
  <script>content/edit-overrides.js</script>
The page applies the overrides when it loads and re-reads content/overrides.json, so Everett's text wins over
whatever the builders wrote. Builders, sweeps and the Night Ledger never write content/overrides.json.

usage: python3 apply_overrides.py [SITE_ROOT]      (default: repo root)
Run it after every page rebuild (refresh.sh does) and before the sanitize step.
"""
import json, re, sys
from datetime import datetime, timezone
from pathlib import Path

MARK = "<!--EDITOV-->"
ROOT = Path(__file__).resolve().parents[2]


def parse_ts(s):
    try:
        return datetime.fromisoformat(str(s).replace("Z", "+00:00"))
    except Exception:
        return None


def active(o, now=None):
    if not isinstance(o, dict) or not isinstance(o.get("text"), str) or not o["text"].strip():
        return False
    if not o.get("expires"):
        return True
    t = parse_ts(o["expires"])
    return bool(t and t.tzinfo and t > (now or datetime.now(timezone.utc)))


def load(root):
    sec = json.loads((root / "content/sections.json").read_text(encoding="utf-8"))
    ovp = root / "content/overrides.json"
    ov = json.loads(ovp.read_text(encoding="utf-8")).get("overrides", {}) if ovp.exists() else {}
    js = (root / "content/edit-overrides.js").read_text(encoding="utf-8")
    return sec, ov, js


def page_state(sec, ov, page, now=None):
    secs = [s for s in sec["sections"] if page in s.get("pages", [])]
    ids = {s["id"] for s in secs}
    return {"page": page, "base": "../", "sections": secs,
            "overrides": {k: v for k, v in ov.items() if k in ids and active(v, now)}}


def inline_js(js):
    """The page copy of edit-overrides.js: comment-free, no runs of spaces (the site scrub collapses them)."""
    js = re.sub(r"/\*.*?\*/", "", js, flags=re.S)
    js = "\n".join(l.strip() for l in js.splitlines() if l.strip() and not l.strip().startswith("//"))
    return re.sub(r" {2,}", " ", js)


def block(state, js):
    js = inline_js(js)
    data = json.dumps(state, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return (f'{MARK}<script id="edit-ov" type="application/json">{data}</script>'
            f'<script>{js.strip()}\nwindow.AttacheOV.boot();</script>{MARK}')


def inject(html, blk):
    html = re.sub(re.escape(MARK) + ".*?" + re.escape(MARK), "", html, flags=re.S)
    i = html.rfind("</body>")
    return html[:i] + blk + html[i:] if i >= 0 else html + blk


def read_block(html):
    m = re.search(re.escape(MARK) + r'<script id="edit-ov" type="application/json">(.*?)</script><script>(.*?)\nwindow\.AttacheOV\.boot\(\);</script>' + re.escape(MARK), html, re.S)
    if not m:
        return None, None
    return json.loads(m.group(1).replace("<\\/", "</")), m.group(2)


def main(root=ROOT):
    root = Path(root)
    sec, ov, js = load(root)
    for page, rel in sec["pages"].items():
        f = root / rel
        if not f.exists():
            continue
        t = f.read_text(encoding="utf-8")
        n = inject(t, block(page_state(sec, ov, page), js))
        if n != t:
            f.write_text(n, encoding="utf-8")
        print("edit overrides ->", page, len(page_state(sec, ov, page)["overrides"]), "active")




def guard_rules():
    """Words /edit/ refuses to save: anything the public-name tests, the site sanitizer or the scrubs would catch."""
    desk = Path(__file__).resolve().parent
    sys.path.insert(0, str(desk))
    import site_sanitize as S
    from tests import test_public_names as T
    rules = [
        {"re": T.BANNED.pattern, "why": "source names can't appear on the public site"},
        {"re": T.JARGON, "why": "source-specific wording the public pages can't carry"},
        {"re": "|".join(re.escape(n) for n in S.NAMES), "why": "a saved account or source name (the site would rename it)"},
        {"re": r"(?:x|twitter)\.com", "why": "links to X can't appear on the public site"},
        {"re": r"yahoo|alpaca", "why": "data vendor names are scrubbed from the site"},
        {"re": r"\bORB\s*(?:5|30)\b", "why": "only ORB15 is shown on the site"},
        {"re": r"\bpaper\b", "why": "the site scrub removes this word from public pages"},
        {"re": r"\be" + r"rror\b", "why": "the site never shows this word; say 'awaiting update' or 'unavailable'"},
        {"re": r"[<>]", "why": "plain text only (use **bold** for emphasis)"},
    ]
    return {"about": "Generated by apply_overrides.py from the public-name tests and site_sanitize. Do not hand-edit.", "rules": rules}


def write_guard(root=ROOT):
    p = Path(root) / "pipeline/desk/edit_guard.json"
    s = json.dumps(guard_rules(), indent=1, ensure_ascii=False) + "\n"
    if not p.exists() or p.read_text(encoding="utf-8") != s:
        p.write_text(s, encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ROOT)
    write_guard()
